const fs = require('node:fs');
const path = require('node:path');
const vm = require('node:vm');
const root = path.resolve(__dirname, '..');
const coreModules = ['src/core/filters.mjs', 'src/core/backup.mjs', 'src/core/storage-operations.mjs'];
const officialModules = ['src/adapters/fanqie/bookshelf-client.mjs'];
const supportModules = ['src/adapters/fanqie/font-map.mjs', 'src/adapters/fanqie/text-reader.mjs', 'src/services/analysis-service.mjs'];
const moduleFiles = [...coreModules, ...officialModules, ...supportModules];
const read = file => fs.readFileSync(path.join(root, file), 'utf8').replace(/\r\n/g, '\n');
const boundary = (file, text) => `\n// SOURCE: ${file}\n${text.trim()}\n`;

// Deliberately small composer, not a general JavaScript bundler.
// The supported ESM form is local named imports and named function/list exports.
function flatten(file) {
  let code = read(file);
  code = code.replace(/^import\s+\{([^}]+)\}\s+from\s+['"]([^'"]+)['"];\s*$/gm, (_, names, specifier) => {
    if (!specifier.startsWith('.')) throw Error(`不支持外部模块：${file}: ${specifier}`);
    const target = path.posix.normalize(path.posix.join(path.posix.dirname(file), specifier));
    if (!moduleFiles.includes(target)) throw Error(`模块未列入构建：${target}`);
    if (!names.split(',').every(name => /^[A-Za-z_$][\w$]*$/.test(name.trim()))) throw Error(`暂不支持别名导入：${file}`);
    return '';
  });
  code = code.replace(/^export\s+\{[\w$,\s]+\};\s*$/gm, '').replace(/^export (?=(?:async )?function\s)/gm, '');
  if (/^\s*(?:import\s|export\s)/m.test(code) || /\bimport\s*\(/.test(code)) throw Error(`不支持的模块语法：${file}`);
  return boundary(file, code);
}

function outputs() {
  const pkg = JSON.parse(read('package.json'));
  const runtime = JSON.parse(read('src/app/runtime.json'));
  if (!Array.isArray(runtime) || new Set(runtime).size !== runtime.length ||
      !runtime.every(file => /^src\/[\w/.-]+\.js$/.test(file) && !file.includes('..'))) throw Error('无效的运行时清单');
  const core = coreModules.map(flatten).join('');
  const userScript = read('src/platform/userscript/header.txt').replace('__VERSION__', pkg.version) +
    '\n// GENERATED by scripts/build.cjs. Edit src/, not this file.\n(async () => {\n\'use strict\';\n' +
    "if (document.getElementById('fq-keyword-filter-host')) return;\n" +
    '// HISTORY_CORE_BEGIN\n' + core + '// HISTORY_CORE_END\n' +
    '// OFFICIAL_CORE_BEGIN\n' + officialModules.map(flatten).join('') + '// OFFICIAL_CORE_END\n' +
    supportModules.map(flatten).join('') + runtime.map(file => boundary(file, read(file))).join('') + '\n})();\n';
  const content = '// GENERATED by scripts/build.cjs. GPL-3.0-only.\n(async () => {\n' +
    boundary('src/platform/chrome/adapter.js', read('src/platform/chrome/adapter.js')) + userScript +
    "\n})().catch(error => console.error('[番茄关键词屏蔽] 初始化失败', error));\n";
  const manifest = {
    manifest_version: 3, name: '番茄小说 · 二游关键词屏蔽', version: pkg.version,
    description: '在番茄书库和排行榜过滤指定题材，自动记录命中书籍，支持待处理清单与导出。',
    permissions: ['storage'], background: {service_worker: 'background.js'},
    content_scripts: [{matches: ['https://fanqienovel.com/*', 'https://www.fanqienovel.com/*'], js: ['content.js'], run_at: 'document_idle', all_frames: false}]
  };
  const result = {
    'fanqie-keyword-filter.user.js': userScript,
    'chrome-extension/content.js': content,
    'chrome-extension/history-core.js': '// GENERATED by scripts/build.cjs. GPL-3.0-only.\n' + core,
    'chrome-extension/background.js': read('src/platform/chrome/background.js'),
    'chrome-extension/manifest.json': JSON.stringify(manifest, null, 2) + '\n',
    'chrome-extension/LICENSE.txt': read('LICENSE.txt'),
    'chrome-extension/第三方来源与许可.md': read('docs/legal/第三方来源与许可.md')
  };
  for (const [file, code] of Object.entries(result)) if (file.endsWith('.js')) new vm.Script(code, {filename: file});
  return result;
}

function build({check = false} = {}) {
  const result = outputs();
  for (const [file, text] of Object.entries(result)) {
    if (check) {
      if (!fs.existsSync(path.join(root, file)) || read(file) !== text) throw Error(`构建产物未更新，请运行 npm run build：${file}`);
    } else {
      fs.mkdirSync(path.dirname(path.join(root, file)), {recursive: true});
      fs.writeFileSync(path.join(root, file), text);
    }
  }
  console.log(check ? '构建产物与源码一致。' : '已生成 Chrome／Edge 扩展与油猴脚本。');
}
if (require.main === module) build();
module.exports = {build, outputs, moduleFiles, root};
